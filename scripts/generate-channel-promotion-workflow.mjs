#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import YAML from "yaml";
import { writeWorkflowSource } from "../packages/core/workflow/workflow-taxonomy.mjs";

const root = path.resolve(import.meta.dirname, "..");
const routedOutputs = {
  "buildchain-channel": "channel",
  "promotion-router-ref": "router-ref",
  "promotion-router-sha": "router-sha",
  "promotion-shell-ref": "shell-ref",
  "promotion-shell-sha": "shell-sha",
  "promotion-runtime-ref": "runtime-ref",
  "promotion-runtime-sha": "runtime-sha",
  "promotion-contract-lock-path": "contract-lock-path",
  "promotion-contract-lock-digest": "contract-lock-digest",
  "promotion-publication-channel": "publication-channel",
  "promotion-target-ref": "target-ref",
  "promotion-override-used": "override-used",
};
export function generateChannelPromotionWorkflow(source) {
  const component = YAML.parse(source).on.workflow_call;
  if (Object.keys(component.inputs).join() !== "request-json") throw new Error("Promotion component requires one complete invocation request");
  const outputs = Object.fromEntries(Object.entries(routedOutputs).map(([key, value]) => [key, {
    description: `Admitted ${value}.`, value: `\${{ jobs.resolve-promotion.outputs.${value} }}`,
  }]));
  for (const [key, output] of Object.entries(component.outputs)) outputs[key] = { ...output, value: `\${{ jobs.invoke.outputs.${key} }}` };
  const jobs = JSON.parse(fs.readFileSync(path.join(root, "architecture/promotion-job-topology.json"), "utf8"));
  jobs.invoke = {
    name: "Invoke the current publisher component", needs: ["resolve-promotion", "consumer-admission"],
    uses: "./.github/workflows/.release-promote.yml", with: { "request-json": "${{ needs.consumer-admission.outputs.invocation-json }}" }, secrets: "inherit",
  };
  return "# Generated by scripts/generate-channel-promotion-workflow.mjs. Do not edit directly.\n" + YAML.stringify({
    name: "Release Candidate Promote",
    on: { workflow_call: { inputs: { "request-json": {
      description: "JSON object matching contracts/promotion-request-v1.schema.json. The API validates types, defaults and authority before dispatch.",
      required: true, type: "string",
    } }, secrets: component.secrets, outputs } }, jobs,
  }, { lineWidth: 0, aliasDuplicateObjects: false });
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url))
  writeWorkflowSource(root, ".github/workflows/public-release-promote.yml", generateChannelPromotionWorkflow(fs.readFileSync(path.join(root, ".github/workflows/.release-promote.yml"), "utf8")));
